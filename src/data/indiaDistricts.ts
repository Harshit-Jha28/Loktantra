function normalise(val: string): string {
  return val.toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]/g, "");
}

/**
 * Returns the list of districts for a state or union territory by name or ID.
 */
export function getDistrictsForState(stateNameOrId: string): string[] {
  const norm = normalise(stateNameOrId);
  for (const [stateName, districts] of Object.entries(INDIA_DISTRICTS)) {
    const n = normalise(stateName);
    if (n === norm || n.includes(norm) || norm.includes(n)) {
      return districts;
    }
  }
  return [];
}
